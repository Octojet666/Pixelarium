package studio.pixelarium.forge;

import java.util.ArrayDeque;
import java.util.Deque;
import java.util.List;
import studio.pixelarium.forge.OpeningData.Ember;
import studio.pixelarium.forge.OpeningData.Layer;
import studio.pixelarium.forge.OpeningData.Letter;
import studio.pixelarium.forge.OpeningData.Mist;
import studio.pixelarium.forge.OpeningData.Palette;
import studio.pixelarium.forge.OpeningData.Wordmark;
import studio.pixelarium.forge.SceneData.Color;
import studio.pixelarium.forge.SceneData.Peak;
import studio.pixelarium.forge.SceneData.SkyStop;
import studio.pixelarium.forge.SceneData.Star;

/**
 * Writes {@link OpeningData} as pretty-printed JSON.
 *
 * <p>Same hand-rolled, stable-key-order approach as {@link JsonWriter}: no third-party dependency, and
 * a regeneration that changes nothing produces a byte-identical file, which is what makes
 * {@code --opening-check} a useful drift guard.</p>
 */
public final class OpeningJson {

  private static final class Frame {
    int items;
  }

  private final StringBuilder out = new StringBuilder(48 * 1024);
  private final Deque<Frame> stack = new ArrayDeque<>();

  public static String toJson(OpeningData scene) {
    OpeningJson writer = new OpeningJson();
    writer.writeScene(scene);
    writer.out.append('\n');
    return writer.out.toString();
  }

  private void writeScene(OpeningData scene) {
    openObject();
    field("$comment", "Generated by tools/scene-forge. Do not edit by hand; run tools/scene-forge/run.sh --opening.");

    fieldName("settings");
    openObject();
    field("width", scene.settings().width());
    field("height", scene.settings().height());
    field("horizon", scene.settings().horizon());
    field("seed", scene.settings().seed());
    field("fps", scene.settings().fps());
    field("drift", scene.settings().drift());
    closeObject();

    fieldName("palette");
    writePalette(scene.palette());

    fieldName("layers");
    openArray();
    for (Layer layer : scene.layers()) writeLayer(layer);
    closeArray();

    fieldName("stars");
    openArray();
    for (Star star : scene.stars()) {
      openItemObject();
      field("x", star.x());
      field("y", star.y());
      field("phase", star.phase());
      field("warm", star.warm());
      closeObject();
    }
    closeArray();

    fieldName("gate");
    openObject();
    field("cx", scene.gate().cx());
    field("baseY", scene.gate().baseY());
    field("radius", scene.gate().radius());
    field("thickness", scene.gate().thickness());
    field("rise", scene.gate().rise());
    colorField("stone", scene.gate().stone());
    colorField("stoneShade", scene.gate().stoneShade());
    colorField("stoneRim", scene.gate().stoneRim());
    colorField("glowCore", scene.gate().glowCore());
    colorField("glowMid", scene.gate().glowMid());
    colorField("glowEdge", scene.gate().glowEdge());
    closeObject();

    fieldName("path");
    openObject();
    field("cx", scene.path().cx());
    field("topY", scene.path().topY());
    field("topHalf", scene.path().topHalf());
    field("bottomY", scene.path().bottomY());
    field("bottomHalf", scene.path().bottomHalf());
    colorField("color", scene.path().color());
    colorField("edge", scene.path().edge());
    closeObject();

    fieldName("embers");
    openArray();
    for (Ember ember : scene.embers()) {
      openItemObject();
      field("x", ember.x());
      field("y", ember.y());
      field("phase", ember.phase());
      field("speed", ember.speed());
      field("rise", ember.rise());
      closeObject();
    }
    closeArray();

    fieldName("mist");
    openArray();
    for (Mist band : scene.mist()) {
      openItemObject();
      field("y", band.y());
      field("thickness", band.thickness());
      field("speed", band.speed());
      field("alpha", band.alpha());
      colorField("color", band.color());
      closeObject();
    }
    closeArray();

    fieldName("wordmark");
    writeWordmark(scene.wordmark());

    closeObject();
  }

  private void writePalette(Palette palette) {
    openObject();
    fieldName("skyStops");
    openArray();
    for (SkyStop stop : palette.skyStops()) {
      openItemObject();
      field("at", stop.at());
      fieldName("color");
      writeColor(stop.color());
      closeObject();
    }
    closeArray();
    colorField("moon", palette.moon());
    colorField("moonHighlight", palette.moonHighlight());
    colorField("moonHalo", palette.moonHalo());
    colorField("starCool", palette.starCool());
    colorField("starWarm", palette.starWarm());
    colorField("mist", palette.mist());
    colorField("ember", palette.ember());
    colorField("emberHot", palette.emberHot());
    colorField("ground", palette.ground());
    colorField("groundShade", palette.groundShade());
    colorField("glyph", palette.glyph());
    colorField("glyphShadow", palette.glyphShadow());
    colorField("glyphGlow", palette.glyphGlow());
    closeObject();
  }

  private void writeLayer(Layer layer) {
    openItemObject();
    field("name", layer.name());
    field("baseY", layer.baseY());
    colorField("body", layer.body());
    colorField("shade", layer.shade());
    colorField("rim", layer.rim());
    field("parallax", layer.parallax());
    fieldName("peaks");
    openArray();
    for (Peak peak : layer.peaks()) {
      openItemObject();
      field("x", peak.x());
      field("height", peak.height());
      field("spread", peak.spread());
      closeObject();
    }
    closeArray();
    closeObject();
  }

  private void writeWordmark(Wordmark wordmark) {
    openObject();
    field("text", wordmark.text());
    field("x", wordmark.x());
    field("y", wordmark.y());
    field("letterWidth", wordmark.letterWidth());
    field("letterHeight", wordmark.letterHeight());
    field("letterGap", wordmark.letterGap());
    fieldName("letters");
    openArray();
    for (Letter letter : wordmark.letters()) {
      openItemObject();
      field("char", String.valueOf(letter.ch()));
      field("x", letter.x());
      field("y", letter.y());
      fieldName("runs");
      writeRuns(letter.runs());
      closeObject();
    }
    closeArray();
    closeObject();
  }

  /** Runs are written inline, one per line: readable, and still one pixel span per JSON line. */
  private void writeRuns(int[][] runs) {
    out.append('[');
    stack.push(new Frame());
    for (int[] run : runs) {
      beginItem();
      List<Integer> values = List.of(run[0], run[1], run[2], run[3]);
      out.append('[');
      for (int i = 0; i < values.size(); i++) {
        if (i > 0) out.append(", ");
        out.append(values.get(i));
      }
      out.append(']');
    }
    closeArray();
  }

  /* ------------------------------------------------------------------ */
  /* Structure                                                           */
  /* ------------------------------------------------------------------ */

  private void openObject() {
    out.append('{');
    stack.push(new Frame());
  }

  private void openItemObject() {
    beginItem();
    openObject();
  }

  private void closeObject() {
    Frame frame = stack.pop();
    if (frame.items > 0) {
      out.append('\n');
      indent();
    }
    out.append('}');
  }

  private void openArray() {
    out.append('[');
    stack.push(new Frame());
  }

  private void closeArray() {
    Frame frame = stack.pop();
    if (frame.items > 0) {
      out.append('\n');
      indent();
    }
    out.append(']');
  }

  private void beginItem() {
    Frame frame = stack.peek();
    if (frame == null) return;
    if (frame.items > 0) out.append(',');
    out.append('\n');
    frame.items++;
    indent();
  }

  private void indent() {
    for (int i = 0; i < stack.size(); i++) out.append("  ");
  }

  /* ------------------------------------------------------------------ */
  /* Values                                                              */
  /* ------------------------------------------------------------------ */

  private void fieldName(String name) {
    beginItem();
    out.append('"').append(escape(name)).append("\": ");
  }

  private void field(String name, int value) {
    fieldName(name);
    out.append(value);
  }

  private void field(String name, double value) {
    fieldName(name);
    out.append(number(value));
  }

  private void field(String name, boolean value) {
    fieldName(name);
    out.append(value);
  }

  private void field(String name, String value) {
    fieldName(name);
    out.append('"').append(escape(value)).append('"');
  }

  private void colorField(String name, Color color) {
    fieldName(name);
    writeColor(color);
  }

  private void writeColor(Color color) {
    out.append('[').append(color.r()).append(", ").append(color.g()).append(", ").append(color.b()).append(']');
  }

  private static String number(double value) {
    if (value == Math.rint(value) && Math.abs(value) < 1e15) {
      return Long.toString((long) value);
    }
    return Double.toString(value);
  }

  private static String escape(String value) {
    StringBuilder escaped = new StringBuilder(value.length());
    for (int i = 0; i < value.length(); i++) {
      char c = value.charAt(i);
      switch (c) {
        case '"' -> escaped.append("\\\"");
        case '\\' -> escaped.append("\\\\");
        case '\n' -> escaped.append("\\n");
        case '\r' -> escaped.append("\\r");
        case '\t' -> escaped.append("\\t");
        default -> escaped.append(c);
      }
    }
    return escaped.toString();
  }
}
