package studio.pixelarium.forge;

import java.util.ArrayDeque;
import java.util.Deque;
import studio.pixelarium.forge.SceneData.Bird;
import studio.pixelarium.forge.SceneData.Cloud;
import studio.pixelarium.forge.SceneData.CloudBand;
import studio.pixelarium.forge.SceneData.Color;
import studio.pixelarium.forge.SceneData.Firefly;
import studio.pixelarium.forge.SceneData.Peak;
import studio.pixelarium.forge.SceneData.Ridge;
import studio.pixelarium.forge.SceneData.SkyStop;
import studio.pixelarium.forge.SceneData.Star;

/**
 * Writes {@link SceneData} as pretty-printed JSON.
 *
 * <p>Hand-rolled on purpose: the tool has to run from a bare JDK with no Maven/Gradle download, so it
 * cannot depend on Jackson or Gson. Output is stable (fixed key order, one item per line), which keeps
 * the generated file readable and its git diffs small.</p>
 */
public final class JsonWriter {

  private static final class Frame {
    int items;
  }

  private final StringBuilder out = new StringBuilder(32 * 1024);
  private final Deque<Frame> stack = new ArrayDeque<>();

  public static String toJson(SceneData scene) {
    JsonWriter writer = new JsonWriter();
    writer.writeScene(scene);
    writer.out.append('\n');
    return writer.out.toString();
  }

  private void writeScene(SceneData scene) {
    openObject();
    field("$comment", "Generated by tools/scene-forge. Do not edit by hand; run tools/scene-forge/run.sh --all.");

    fieldName("settings");
    openObject();
    field("width", scene.settings().width());
    field("height", scene.settings().height());
    field("horizon", scene.settings().horizon());
    field("seed", scene.settings().seed());
    field("fps", scene.settings().fps());
    closeObject();

    fieldName("palette");
    writePalette(scene.palette());

    fieldName("farRidge");
    writeRidge(scene.farRidge());

    fieldName("nearRidge");
    writeRidge(scene.nearRidge());

    fieldName("stars");
    openArray();
    for (Star star : scene.stars()) {
      openItemObject();
      field("x", star.x());
      field("y", star.y());
      field("phase", star.phase());
      field("warm", star.warm());
      closeObject();
    }
    closeArray();

    fieldName("cloudBands");
    openArray();
    for (CloudBand band : scene.cloudBands()) {
      writeBand(band);
    }
    closeArray();

    fieldName("fireflies");
    openArray();
    for (Firefly fly : scene.fireflies()) {
      openItemObject();
      field("x", fly.x());
      field("y", fly.y());
      field("phase", fly.phase());
      field("speed", fly.speed());
      closeObject();
    }
    closeArray();

    fieldName("birds");
    openArray();
    for (Bird bird : scene.birds()) {
      openItemObject();
      field("start", bird.start());
      field("y", bird.y());
      field("speed", bird.speed());
      field("phase", bird.phase());
      closeObject();
    }
    closeArray();

    closeObject();
  }

  private void writePalette(SceneData.Palette palette) {
    openObject();
    fieldName("skyStops");
    openArray();
    for (SkyStop stop : palette.skyStops()) {
      openItemObject();
      field("at", stop.at());
      fieldName("color");
      writeColor(stop.color());
      closeObject();
    }
    closeArray();
    colorField("sunCore", palette.sunCore());
    colorField("sunMid", palette.sunMid());
    colorField("sunOuter", palette.sunOuter());
    colorField("sunHalo", palette.sunHalo());
    colorField("moon", palette.moon());
    colorField("moonHighlight", palette.moonHighlight());
    colorField("moonHalo", palette.moonHalo());
    colorField("starWarm", palette.starWarm());
    colorField("starCool", palette.starCool());
    colorField("reflectionNear", palette.reflectionNear());
    colorField("reflectionFar", palette.reflectionFar());
    colorField("firefly", palette.firefly());
    colorField("bird", palette.bird());
    colorField("waterTop", palette.waterTop());
    colorField("waterBottom", palette.waterBottom());
    colorField("waterSheen", palette.waterSheen());
    closeObject();
  }

  private void writeRidge(Ridge ridge) {
    openObject();
    field("name", ridge.name());
    field("baseY", ridge.baseY());
    colorField("body", ridge.body());
    colorField("shade", ridge.shade());
    colorField("rim", ridge.rim());
    fieldName("peaks");
    openArray();
    for (Peak peak : ridge.peaks()) {
      openItemObject();
      field("x", peak.x());
      field("height", peak.height());
      field("spread", peak.spread());
      closeObject();
    }
    closeArray();
    closeObject();
  }

  private void writeBand(CloudBand band) {
    openItemObject();
    field("name", band.name());
    field("yFrom", band.yFrom());
    field("yTo", band.yTo());
    field("count", band.count());
    field("speed", band.speed());
    colorField("color", band.color());
    colorField("topColor", band.topColor());
    field("alpha", band.alpha());
    field("behindRidges", band.behindRidges());
    fieldName("clouds");
    openArray();
    for (Cloud cloud : band.clouds()) {
      openItemObject();
      field("x", cloud.x());
      field("y", cloud.y());
      field("rx", cloud.rx());
      field("ry", cloud.ry());
      field("speed", cloud.speed());
      closeObject();
    }
    closeArray();
    closeObject();
  }

  /* ------------------------------------------------------------------ */
  /* Structure                                                           */
  /* ------------------------------------------------------------------ */

  private void openObject() {
    out.append('{');
    stack.push(new Frame());
  }

  /** Starts an object that is an array element, so it gets its own comma and line. */
  private void openItemObject() {
    beginItem();
    openObject();
  }

  private void closeObject() {
    Frame frame = stack.pop();
    if (frame.items > 0) {
      out.append('\n');
      indent();
    }
    out.append('}');
  }

  private void openArray() {
    out.append('[');
    stack.push(new Frame());
  }

  private void closeArray() {
    Frame frame = stack.pop();
    if (frame.items > 0) {
      out.append('\n');
      indent();
    }
    out.append(']');
  }

  /** Emits the separator, newline and indentation that precede an object member or array element. */
  private void beginItem() {
    Frame frame = stack.peek();
    if (frame == null) {
      return;
    }
    if (frame.items > 0) {
      out.append(',');
    }
    out.append('\n');
    frame.items++;
    indent();
  }

  private void indent() {
    for (int i = 0; i < stack.size(); i++) {
      out.append("  ");
    }
  }

  /* ------------------------------------------------------------------ */
  /* Values                                                              */
  /* ------------------------------------------------------------------ */

  private void fieldName(String name) {
    beginItem();
    out.append('"').append(escape(name)).append("\": ");
  }

  private void field(String name, int value) {
    fieldName(name);
    out.append(value);
  }

  private void field(String name, double value) {
    fieldName(name);
    out.append(number(value));
  }

  private void field(String name, boolean value) {
    fieldName(name);
    out.append(value);
  }

  private void field(String name, String value) {
    fieldName(name);
    out.append('"').append(escape(value)).append('"');
  }

  private void colorField(String name, Color color) {
    fieldName(name);
    writeColor(color);
  }

  private void writeColor(Color color) {
    out.append('[').append(color.r()).append(", ").append(color.g()).append(", ").append(color.b()).append(']');
  }

  /** Shortest round-tripping representation, so the JSON carries the exact double values. */
  private static String number(double value) {
    if (value == Math.rint(value) && Math.abs(value) < 1e15) {
      return Long.toString((long) value);
    }
    return Double.toString(value);
  }

  private static String escape(String value) {
    StringBuilder escaped = new StringBuilder(value.length());
    for (int i = 0; i < value.length(); i++) {
      char c = value.charAt(i);
      switch (c) {
        case '"' -> escaped.append("\\\"");
        case '\\' -> escaped.append("\\\\");
        case '\n' -> escaped.append("\\n");
        case '\r' -> escaped.append("\\r");
        case '\t' -> escaped.append("\\t");
        default -> escaped.append(c);
      }
    }
    return escaped.toString();
  }
}
